export const words = new Map(wordSource.split("\n").map((line) => line.split("|")));
const dictionary = [...words.keys()];
export function differences(a, b) {
  let count = 0;
  for (let i = 0; i < a.length; i++) if (a[i] !== b[i]) count++;
  return count;
}
const neighbors = new Map(dictionary.map((word) => [word, dictionary.filter((other) => differences(word, other) === 1)]));

export function makeLadder(seed) {
  const rng = randomStream(seed);
  const length = 6 + Math.floor(rng.next() * 2);
  for (let attempt = 0; attempt < 80; attempt++) {
    const path = [rng.pick(dictionary)];
    while (path.length < length) {
      const choices = neighbors.get(path.at(-1)).filter((candidate) => !path.includes(candidate) && path.slice(0, -1).every((old) => differences(candidate, old) > 1));
      if (!choices.length) break;
      path.push(rng.pick(choices));
    }
    if (path.length === length) return path;
  }
  return ["cold", "cord", "card", "ward", "warm", "worm"];
}

