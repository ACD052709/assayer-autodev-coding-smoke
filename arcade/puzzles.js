export const themes = threadSource.split("\n").map((line, index) => {
  const [, title, clues, decoys] = line.split("|");
  return { id: "c" + index.toString(36), title, clues: clues.split(","), decoys: decoys.split(",") };
});

export function makeThread(seed, id) {
  const theme = themes.find((entry) => entry.id === id) ?? themes[seed % themes.length];
  const rng = randomStream(seed ^ 0xbac1c54d);
  return { ...theme, clues: [...rng.shuffle(theme.clues.slice(0, 2)), ...theme.clues.slice(2)], options: rng.shuffle([theme.title, ...theme.decoys]) };
}

export function dailyEdition(now = Date.now()) {
  const day = Math.floor(now / 86400000);
  return { seed: Math.imul(day, 0x9e3779b1) >>> 0, theme: themes[(day % themes.length + themes.length) % themes.length].id, date: new Date(day * 86400000) };
}
